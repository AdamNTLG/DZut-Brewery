  /// Recherche par texte (nom, catégorie, type de fermentation)
  static List<BeerStyle> search(String query) {
    if (query.isEmpty) return all;
    final q = query.toLowerCase();
    return all.where((s) =>
      s.name.toLowerCase().contains(q) ||
      s.category.toLowerCase().contains(q) ||
      (s.fermentationType?.toLowerCase().contains(q) ?? false) ||
      (s.description?.toLowerCase().contains(q) ?? false)
    ).toList();
  }

  /// Styles groupés par catégorie
  static Map<String, List<BeerStyle>> get byCategory {
    final map = <String, List<BeerStyle>>{};
    for (final s in all) {
      map.putIfAbsent(s.category, () => []).add(s);
    }
    return map;
  }

  /// Styles groupés par type de fermentation
  static Map<String, List<BeerStyle>> get byFermentationType {
    final map = <String, List<BeerStyle>>{};
    for (final s in all) {
      map.putIfAbsent(s.fermentationType ?? 'Autre', () => []).add(s);
    }
    return map;
  }

  /// Liste des catégories uniques
  static List<String> get categories => byCategory.keys.toList();

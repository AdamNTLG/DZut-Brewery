  // Conversion Plato → Densité spécifique (SG)
  static double _p(double plato) {
    if (plato <= 0) return 1.000;
    return 1.0 + plato / (258.6 - 0.8796 * plato);
  }

  // EBC → SRM (SRM = EBC / 1.97)
  static double _e(double ebc) => ebc > 0 ? ebc / 1.97 : 0;

  // Constructeur compact pour un style BA
  static BeerStyle _ba(
    String ft,      // fermentation type
    String cat,     // category
    String name,    // style name
    double ogN, double ogX,   // OG Plato min/max
    double fgN, double fgX,   // FG Plato min/max
    double abvN, double abvX, // ABV %
    double ibuN, double ibuX, // IBU
    double ebcN, double ebcX, // EBC (0 = unbounded)
    String color,
    String body,
    String descEn,
    String descFr,
  ) =>
      BeerStyle(
        id: name,
        category: cat,
        name: name,
        fermentationType: ft,
        ogMin: _p(ogN),
        ogMax: _p(ogX > 0 ? ogX : ogN),
        fgMin: _p(fgN),
        fgMax: _p(fgX > 0 ? fgX : fgN),
        abvMin: abvN,
        abvMax: abvX,
        ibuMin: ibuN,
        ibuMax: ibuX > 0 ? ibuX : 100,
        srmMin: _e(ebcN),
        srmMax: _e(ebcX > 0 ? ebcX : 200),
        colorDescription: color,
        body: body,
        description: descEn,
        descriptionFr: descFr,
      );

